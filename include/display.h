// 用途：计时与计分数码管显示接口声明。
//
// 声明计时拆位、比分拆位和每毫秒扫描一位数码管的三个函数。
// 具体函数体和模块内部变量位于 src/display.c；本文件负责告诉其他模块有哪些接口可用。
// 其他 .c 通过 #include 引入本头文件，再调用声明过的函数。
// extern 只声明共享变量的名字，不分配第二份变量；头文件保护宏避免重复声明引起的问题。
// ============================================================================

#ifndef DISPLAY_H
#define DISPLAY_H

#include "board.h"

// 数码管动态扫描模块对外接口。
// .h 里只声明名字；变量的存储空间及函数实现由对应 .c 提供。

// 函数用途：update_display() —— 生成计时数码管要显示的四位数字。
// 工作说明：读取剩余总秒数，拆成分钟十位、分钟个位、秒十位、秒个位，写入显示数组的前四项。
void update_display(void);                                                      // 实现在 display.c
// 函数用途：update_score_display() —— 生成计分数码管要显示的四位数字。
// 工作说明：把 A、B 两队分数各拆成十位和个位，写入显示数组的后四项，并清除比分刷新标记。
void update_score_display(void);                                                // 实现在 display.c
// 函数用途：scan_one_digit() —— 执行一次数码管动态扫描。
// 工作说明：先关闭全部位选，再写入当前位的段码并选中这一位；每 1 毫秒调用一次，八位循环显示。
void scan_one_digit(void);                                                      // 实现在 display.c

#endif                                                                          // DISPLAY_H
