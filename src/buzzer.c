// ============================================================================
// 文件：src/buzzer.c
// 用途：蜂鸣器提示节奏。
//
// 通过 P1.4 控制蜂鸣器，更新这一毫秒应该鸣叫还是静音。
// 剩余 30 秒时响三声，最后 10 秒循环间歇提示，最后 5 秒加快提示。
// scheduler.c 每 1 毫秒调用 update_alert_output()；暂停或计时归零时关闭输出。
// countdown.c 在相应时间点设置或清除提示计数，本文件负责按计数产生输出节奏。
// ============================================================================

#include "buzzer.h"
#include "countdown.h"

volatile unsigned int alert30_ms = 0;                                           // 30 秒提示还剩多少毫秒
volatile unsigned int beep_phase_ms = 0;                                        // 最后 10 秒提示的周期位置

// 函数用途：update_alert_output() —— 更新蜂鸣器的鸣叫和静音节奏。
// 工作说明：每 1 毫秒调用一次；处理 30 秒三声提示、最后 10 秒间歇提示和最后 5 秒加速提示。
void update_alert_output(void)                                                  // 计算这一毫秒是否需要开启蜂鸣器。
{                                                                               // 开始这一段语句块；配对的右花括号表示这段结束。
    unsigned char alert_on = 0;                                                 // 本次提示输出先设为关闭，下面满足提示条件时才改成 1。
    if (running && remaining_seconds != 0) {                                    // && 表示两项都要成立：正在计时，而且剩余时间不是 0。
        if (remaining_seconds <= 10) {                                          // 最后 10 秒采用循环间歇鸣叫；更早时检查 30 秒三声提示。
            /* “条件 ? A : B”意为：条件成立取 A，否则取 B。
             * 例如最后 5 秒用 200ms 周期、90ms 响；6～10 秒
             * 用 400ms 周期、180ms 响。 */
            unsigned int period = (remaining_seconds <= 5) ? 200 : 400;         // 剩 5 秒及以下用 200 毫秒一个周期，否则用 400 毫秒。
            unsigned int on_time = (remaining_seconds <= 5) ? 90 : 180;         // 对应周期内鸣叫 90 或 180 毫秒，其余时间关闭输出。
            if (beep_phase_ms < on_time) alert_on = 1;                          // 当前周期位置落在鸣叫时间段内，就将本次输出设为开。
            if (++beep_phase_ms >= period) beep_phase_ms = 0;                   // 周期位置每毫秒加 1，达到周期长度后回到 0，开始下一声。
        } else if (alert30_ms != 0) {                                           // 不在最后 10 秒且三声提示还没结束时，继续处理三声提示。
            // 剩余 600～501、400～301、200～101 毫秒时各响 100 毫秒。
            if (alert30_ms > 500 ||                                             // 剩余提示时间在 600～501 毫秒时属于第一声，或者满足后两段之一。
                (alert30_ms <= 400 && alert30_ms > 300) ||                      // 400～301 毫秒属于第二声；区间之间留出安静间隔。
                (alert30_ms <= 200 && alert30_ms > 100))                        // 200～101 毫秒属于第三声，三段任一成立就开启输出。
                alert_on = 1;                                                   // 把本次输出标记设为开，函数末尾据此设置 P1.4。
            --alert30_ms;                                                       // 三声提示剩余时长减少 1 毫秒，减到 0 就结束。
        }                                                                       // 结束这一层语句块，按外层循环、判断或函数的结构继续执行。
    }                                                                           // 结束这一层语句块，按外层循环、判断或函数的结构继续执行。
    if (alert_on) P1 |= ALERT_BIT;                                              // 需要鸣叫时只把 P1.4 置 1，其他 P1 引脚保持原值。
    else P1 &= (unsigned char)~ALERT_BIT;                                       // 否则只清除 P1.4，关闭鸣叫控制输出。
}                                                                               // 结束这一层语句块，按外层循环、判断或函数的结构继续执行。

